/** 汉字 → 首字母 的查表索引（惰性构建，仅一次） */
let charIndex: Map<string, string> | null = null;

const getCharIndex = (): Map<string, string> => {
  if (charIndex) return charIndex;
  const map = new Map<string, string>();
  Object.keys(CHAR_GROUPS).forEach((letter) => {
    for (const ch of CHAR_GROUPS[letter]) {
      if (!map.has(ch)) map.set(ch, letter);
    }
  });
  charIndex = map;
  return map;
};

/** 取单个字符的拼音首字母；非汉字原样返回大写字母/数字 */
export const getCharInitial = (ch: string): string => {
  if (!ch) return "";
  const upper = ch.toUpperCase();
  // 拉丁字母与数字直接作为首字母
  if (/^[A-Z0-9]$/.test(upper)) return upper;
  return getCharIndex().get(ch) ?? upper;
};

/**
 * 取一段文本每个字的首字母，拼成大写串。
 * 例：getInitials("庆余年") => "QYN"；getInitials("流浪地球2") => "LLDQ2"
 * 非汉字（空格、标点）被忽略。
 */
export const getInitials = (text: string): string => {
  if (!text) return "";
  let result = "";
  for (const ch of text) {
    if (/[\s\p{P}\p{S}]/u.test(ch)) continue;
    const initial = getCharInitial(ch);
    // 表外生僻字原样保留，避免污染首字母串时只保留 ASCII
    result += /^[A-Z0-9]$/.test(initial) ? initial : "";
  }
  return result;
};

/** 判断输入是否为纯首字母查询（拉丁字母 / 数字） */
export const isInitialsQuery = (query: string): boolean =>
  /^[A-Za-z0-9\s]+$/.test(query) && /[A-Za-z0-9]/.test(query);

/**
 * 首字母匹配：查询串（大小写不敏感）是目标文本首字母串的前缀或子串即命中。
 * 同时也支持中文原文包含匹配，保证中文输入不受影响。
 */
export const matchesInitials = (text: string, query: string): boolean => {
  if (!query.trim()) return false;
  const q = query.trim();
  if (!isInitialsQuery(q)) {
    return text.toLowerCase().includes(q.toLowerCase());
  }
  const normalized = q.replace(/\s+/g, "").toUpperCase();
  return getInitials(text).includes(normalized);
};
